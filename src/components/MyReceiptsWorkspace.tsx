import React, { useMemo, useState } from 'react';
import { Download, Printer, Receipt, Search, Share2 } from 'lucide-react';
import { SaleRecord } from '../types/pharmacy';
import {
  downloadA5InvoicePdf,
  shareInvoiceSummary,
} from '../services/a5PdfGenerator';

interface MyReceiptsWorkspaceProps {
  sales: SaleRecord[];
  staffName: string;
  onOpenInvoiceModal: (sale: SaleRecord) => void;
}

export const MyReceiptsWorkspace: React.FC<MyReceiptsWorkspaceProps> = ({
  sales,
  staffName,
  onOpenInvoiceModal,
}) => {
  const [search, setSearch] = useState('');
  const [shareNote, setShareNote] = useState<string | null>(null);

  const filteredSales = useMemo(() => {
    const q = search.trim().toLowerCase();
    if (!q) return sales;
    return sales.filter(
      (sale) =>
        sale.invoiceNumber.toLowerCase().includes(q) ||
        sale.paymentMode.toLowerCase().includes(q) ||
        sale.items.some((line) => line.itemName.toLowerCase().includes(q)),
    );
  }, [sales, search]);

  const todaysCount = useMemo(() => {
    const now = new Date();
    const todayKey = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
    return sales.filter((sale) => {
      const dt = new Date(sale.createdAt);
      if (Number.isNaN(dt.getTime())) return false;
      const key = `${dt.getFullYear()}-${String(dt.getMonth() + 1).padStart(2, '0')}-${String(dt.getDate()).padStart(2, '0')}`;
      return key === todayKey;
    }).length;
  }, [sales]);

  const handleShare = async (sale: SaleRecord) => {
    try {
      const outcome = await shareInvoiceSummary(sale);
      setShareNote(
        outcome === 'shared'
          ? `Shared receipt ${sale.invoiceNumber}`
          : `Copied receipt ${sale.invoiceNumber} summary`,
      );
      setTimeout(() => setShareNote(null), 2500);
    } catch {
      setShareNote('Unable to open share dialog');
      setTimeout(() => setShareNote(null), 2500);
    }
  };

  return (
    <div className="flex flex-col gap-5">
      {/* Header & Summary */}
      <section className="flex flex-col justify-between gap-4 rounded-xl border border-slate-200 bg-white p-5 dark:border-slate-800 dark:bg-slate-900 sm:flex-row sm:items-center">
        <div>
          <div className="flex items-center gap-2 text-[#0D7A5F] dark:text-emerald-400">
            <Receipt className="h-4 w-4 shrink-0" />
            <span className="text-xs font-semibold uppercase tracking-wider">
              Counter Receipts
            </span>
          </div>
          <h2 className="mt-1 font-display text-lg font-bold tracking-tight text-slate-900 dark:text-slate-100">
            Receipts Generated by {staffName}
          </h2>
          <p className="mt-0.5 text-xs text-slate-500 dark:text-slate-400">
            View, print, or download A5 PDFs only for bills you generated on POS.
          </p>
        </div>

        <div className="flex items-center gap-6 border-t border-slate-100 pt-3 dark:border-slate-800 sm:border-t-0 sm:pt-0">
          <div>
            <p className="text-[11px] font-medium text-slate-500 dark:text-slate-400">
              Today
            </p>
            <p className="font-mono-tabular text-xl font-bold text-[#0D7A5F] dark:text-emerald-400">
              {todaysCount}
            </p>
          </div>
          <div
            className="h-8 w-px bg-slate-200 dark:bg-slate-800"
            aria-hidden="true"
          />
          <div>
            <p className="text-[11px] font-medium text-slate-500 dark:text-slate-400">
              My Total Bills
            </p>
            <p className="font-mono-tabular text-xl font-bold text-slate-900 dark:text-slate-100">
              {sales.length}
            </p>
          </div>
        </div>
      </section>

      {shareNote && (
        <div
          role="status"
          className="rounded-xl border border-emerald-200 bg-emerald-50 px-4 py-2.5 text-xs font-medium text-emerald-900 dark:border-emerald-800 dark:bg-emerald-950/60 dark:text-emerald-300"
        >
          {shareNote}
        </div>
      )}

      {/* Search Bar */}
      <div className="rounded-xl border border-slate-200 bg-white p-4 dark:border-slate-800 dark:bg-slate-900">
        <div className="relative max-w-md">
          <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-slate-400" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search by invoice #, medicine name, or payment mode..."
            className="w-full rounded-lg border border-slate-300 bg-white py-2 pl-9 pr-3 text-sm text-slate-900 placeholder:text-slate-400 focus:border-[#0D7A5F] focus:outline-none dark:border-slate-700 dark:bg-slate-800 dark:text-slate-100 dark:placeholder:text-slate-500"
          />
        </div>
      </div>

      {/* Read-only Receipts Table */}
      <section className="overflow-hidden rounded-xl border border-slate-200 bg-white dark:border-slate-800 dark:bg-slate-900">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="border-b border-slate-200 bg-slate-50 font-semibold text-slate-600 dark:border-slate-800 dark:bg-slate-800/60 dark:text-slate-300">
              <tr>
                <th className="px-5 py-3">Invoice #</th>
                <th className="px-4 py-3">Date &amp; Time</th>
                <th className="px-4 py-3">Items Billed</th>
                <th className="px-4 py-3">Payment Mode</th>
                <th className="px-4 py-3 text-right">Net Payable</th>
                <th className="px-5 py-3 text-right">Receipt Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
              {filteredSales.length === 0 ? (
                <tr>
                  <td
                    colSpan={6}
                    className="px-5 py-12 text-center text-xs text-slate-500 dark:text-slate-400"
                  >
                    {sales.length === 0
                      ? 'You have not generated any POS receipts in this account yet. Complete a sale in POS Billing to see your receipt here.'
                      : `No receipts match "${search}".`}
                  </td>
                </tr>
              ) : (
                filteredSales.map((sale) => {
                  const totalQty = sale.items.reduce(
                    (sum, line) => sum + line.quantity,
                    0,
                  );
                  const dt = new Date(sale.createdAt);
                  const dateLabel = Number.isNaN(dt.getTime())
                    ? sale.createdAt
                    : dt.toLocaleString('en-PK', {
                        day: '2-digit',
                        month: 'short',
                        year: 'numeric',
                        hour: '2-digit',
                        minute: '2-digit',
                      });

                  return (
                    <tr
                      key={sale.id}
                      className="hover:bg-slate-50/70 dark:hover:bg-slate-800/50"
                    >
                      <td className="px-5 py-3 font-mono-tabular font-semibold text-slate-900 dark:text-slate-100">
                        {sale.invoiceNumber}
                      </td>
                      <td className="px-4 py-3 font-mono-tabular text-slate-600 whitespace-nowrap dark:text-slate-400">
                        {dateLabel}
                      </td>
                      <td className="px-4 py-3 text-slate-700 dark:text-slate-300">
                        <p className="font-medium text-slate-900 dark:text-slate-100">
                          {sale.items.length}{' '}
                          {sale.items.length === 1 ? 'medicine' : 'medicines'} (
                          {totalQty} units)
                        </p>
                        <p className="mt-0.5 max-w-xs truncate text-[11px] text-slate-500 dark:text-slate-400">
                          {sale.items.map((l) => l.itemName).join(', ')}
                        </p>
                      </td>
                      <td className="px-4 py-3 text-slate-700 dark:text-slate-300">
                        {sale.paymentMode}
                      </td>
                      <td className="px-4 py-3 text-right font-mono-tabular font-semibold text-[#0D7A5F] dark:text-emerald-400">
                        PKR {sale.netPayable.toFixed(2)}
                      </td>
                      <td className="px-5 py-3 text-right">
                        <div className="inline-flex items-center gap-1.5">
                          <button
                            type="button"
                            onClick={() => onOpenInvoiceModal(sale)}
                            className="inline-flex items-center gap-1 rounded-md border border-slate-300 bg-white px-2.5 py-1.5 text-xs font-medium text-slate-800 whitespace-nowrap hover:bg-slate-50 dark:border-slate-700 dark:bg-slate-800 dark:text-slate-200 dark:hover:bg-slate-700"
                          >
                            <Printer className="h-3.5 w-3.5" />
                            <span>Receipt</span>
                          </button>
                          <button
                            type="button"
                            onClick={() => downloadA5InvoicePdf(sale)}
                            title="Download A5 PDF"
                            aria-label={`Download A5 PDF for ${sale.invoiceNumber}`}
                            className="rounded-md border border-slate-300 bg-white p-1.5 text-slate-700 hover:bg-slate-50 dark:border-slate-700 dark:bg-slate-800 dark:text-slate-200 dark:hover:bg-slate-700"
                          >
                            <Download className="h-3.5 w-3.5" />
                          </button>
                          <button
                            type="button"
                            onClick={() => void handleShare(sale)}
                            title="Share Receipt"
                            aria-label={`Share ${sale.invoiceNumber}`}
                            className="rounded-md border border-slate-300 bg-white p-1.5 text-slate-700 hover:bg-slate-50 dark:border-slate-700 dark:bg-slate-800 dark:text-slate-200 dark:hover:bg-slate-700"
                          >
                            <Share2 className="h-3.5 w-3.5" />
                          </button>
                        </div>
                      </td>
                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>
      </section>
    </div>
  );
};
